using System;

namespace CLIInterface
{
    namespace Math3D
    {

        //++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
        //
        // Vector2Ex
        //
        //      요약:
        //          Vector2클래스에 대한 확장 메소드입니다.
        //
        //++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++

        public static class Vector2Ex
        {
            //++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
            // 확장 메소드
            //
            //++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++

            #region [확장 메소드] 
            //------------------------------------------------------------------------------------------------------------------------------------------------------
            public static Vector3 ToV3(this Vector2 v) { return new Vector3(v.x, v.y, 0f); }
            //------------------------------------------------------------------------------------------------------------------------------------------------------
            // Multiplies every component of this vector by the same component of /scale/.
            public static void Scale(this Vector2 v, Vector2 scale) { v.x *= scale.x; v.y *= scale.y; }
            //------------------------------------------------------------------------------------------------------------------------------------------------------
            // used to allow Vector2s to be used as keys in hash tables
            public static int GetHashCode(this Vector2 v) { return v.x.GetHashCode() ^ (v.y.GetHashCode() << 2); }
            //------------------------------------------------------------------------------------------------------------------------------------------------------
            public static bool Equals(this Vector2 v, Vector2 other) { return v.x == other.x && v.y == other.y; }
            //------------------------------------------------------------------------------------------------------------------------------------------------------
            // Returns the length of this vector (RO).
            public static float magnitude(this Vector2 v) { return (float)Math.Sqrt(v.x * v.x + v.y * v.y); }
            //------------------------------------------------------------------------------------------------------------------------------------------------------
            // Returns the squared length of this vector (RO).
            public static float sqrMagnitude(this Vector2 v) { return v.x * v.x + v.y * v.y; }
            #endregion

        }
    }
}

