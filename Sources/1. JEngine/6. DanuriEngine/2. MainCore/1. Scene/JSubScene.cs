using System.Collections;

namespace J2y
{
    //++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
    //
    // JSubScene
    //
    //
    //++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++

    public abstract partial class JSubScene
    {
        //++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
        // 변수
        //
        //++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++

        #region [변수]
        private string _name;
        #endregion


        //++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
        // Property
        //
        //++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++

        #region [Property]
        //------------------------------------------------------------------------------------------------------------------------------------------------------
        public string Name
        {
            get
            { return _name; }
            set
            {
                _name = value;
            }
        }
        #endregion


        //++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
        // 기본 함수
        //
        //++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++

        #region [초기화] Begine, End
        //------------------------------------------------------------------------------------------------------------------------------------------------------
        public abstract IEnumerator Begine();
        //------------------------------------------------------------------------------------------------------------------------------------------------------
        public abstract IEnumerator End();
        #endregion

        #region [업데이터] Update
        //------------------------------------------------------------------------------------------------------------------------------------------------------
        public abstract void Update(float deltaTime);
        #endregion

    }

}

