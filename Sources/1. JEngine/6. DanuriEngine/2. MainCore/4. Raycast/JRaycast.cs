using CLIInterface.Math3D;
using J2y.Interface;

namespace J2y
{
    namespace Danuri
    {
        //++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
        //
        // JRaycast
        //
        //
        //++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++

        public partial class JRaycast
        {
            //++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
            //
            // JRaycast.Ray
            //
            //
            //++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++

            public struct Ray
            {
                //++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
                // Ray
                //
                //++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++

                #region [변수] Ray
                private Vector3 _direction;
                private Vector3 _origin;
                #endregion


                //++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
                // Property
                //
                //++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++

                #region [Property]
                //------------------------------------------------------------------------------------------------------------------------------------------------------
                public Vector3 Direction { get { return _direction; } }
                //------------------------------------------------------------------------------------------------------------------------------------------------------
                public Vector3 Origin { get { return _origin; } }
                #endregion


                //++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
                // 기본 함수
                //
                //++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++

                #region [초기화] 생성자
                //------------------------------------------------------------------------------------------------------------------------------------------------------
                public Ray(Vector3 origin, Vector3 direction)
                {
                    _origin = origin;
                    _direction = direction;
                    _direction.Normalize();
                }
                //------------------------------------------------------------------------------------------------------------------------------------------------------
                public Ray(Ray ray)
                {
                    _origin = ray.Origin;
                    _direction = ray.Direction;
                }
                #endregion


                //++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
                // Ray
                //
                //++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++

                #region [Ray] GetPoint
                //------------------------------------------------------------------------------------------------------------------------------------------------------
                public Vector3 GetPoint(float distance) { return Origin + Direction * distance; }
                #endregion


            }


            //++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
            //
            // JRaycast.Hit
            //
            //
            //++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++

            public struct Hit<T> where T : IColliderHandler
            {
                //++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
                // Hit
                //
                //++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++

                #region [변수] RaycastHit
                #endregion


                //++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
                // Property
                //
                //++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++

                #region [Property]
                //------------------------------------------------------------------------------------------------------------------------------------------------------
                public T Collider { get; set; }
                public float Distance { get; set; }
                public Vector3 Point { get; set; }
                #endregion


                //++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
                // 기본 함수
                //
                //++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++

                #region [초기화] 생성자
                //------------------------------------------------------------------------------------------------------------------------------------------------------
                public Hit(T coll, float dist, Vector3 pos)
                {
                    Collider = coll;
                    Distance = dist;
                    Point = pos;
                }
                #endregion

            }
        }
    }
}

