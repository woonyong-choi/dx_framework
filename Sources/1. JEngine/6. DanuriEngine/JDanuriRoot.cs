using CLIInterface;

namespace J2y
{
	namespace Danuri
	{
		//++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
		//
		// JDanuriRoot
		//
		//
		//++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++

		public class JDanuriRoot : Actor
		{
			//++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
			// 변수
			//
			//++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++

			#region [변수] Base
			#endregion



			//++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
			// Property
			//
			//++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++

			#region [Property] Instance
			public JDanuriRoot Instance { get; private set; }
			#endregion

			#region [Property] Managers
			#endregion

			#region [Property] Root
			//------------------------------------------------------------------------------------------------------------------------------------------------------
			public static bool Run { get; set; } = true;
			#endregion

			//++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
			// 기본 함수
			//
			//++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++

			#region [초기화] OnCreate
			//------------------------------------------------------------------------------------------------------------------------------------------------------
			public override int OnCreate()
			{
				base.OnCreate();

				Instance = Instance ?? this;

				JEventHandler.RegisterEvent("JFramework_OnCreate", () =>
				{
				});


				return 0;
			}
			#endregion

			#region [정리] OnDestroy
			//------------------------------------------------------------------------------------------------------------------------------------------------------
			public override int OnDestroy()
			{
				base.OnDestroy();

				Instance = Instance == this ? null : Instance;

				return 0;
			}
			#endregion

			#region [활성화] OnEnable
			//------------------------------------------------------------------------------------------------------------------------------------------------------
			public override int OnEnable()
			{
				base.OnEnable();

				return 0;
			}
			#endregion

			#region [비활성화] OnDisable
			//------------------------------------------------------------------------------------------------------------------------------------------------------
			public override int OnDisable()
			{
				base.OnDisable();

				return 0;
			}
			#endregion

			#region [업데이트] Update
			//------------------------------------------------------------------------------------------------------------------------------------------------------
			public override int Update()
			{
				base.Update();

				JTimer.Update();
				if(Run)
                {
					EventSystem.Update(JTimer.DeltaTime);
					JScene.Manager.Update(JTimer.DeltaTime);
					JActor.Manager.Update(JTimer.DeltaTime);
				}
				return 0;
			}
			#endregion
		}
	}
}

