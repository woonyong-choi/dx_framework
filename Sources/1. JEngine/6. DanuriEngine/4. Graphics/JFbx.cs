using CLIInterface.Fbx;
using CLIInterface.Geometry;
using J2y.Interface;


namespace J2y
{
    namespace Danuri
    {
        //++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
        //
        // JFbx
        //
        //
        //++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++

        public class JFbx : JActor, IFbxColliderHandler
        {
            //++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
            // 변수
            //
            //++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++

            #region [변수] IFbxColliderHandler
            protected Fbx _fbx;
            #endregion

            #region [변수] UseCollider
            protected bool _useCollider = true;
            #endregion


            //++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
            // Property
            //
            //++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++

            #region [Property] IFbxColliderHandler

            //------------------------------------------------------------------------------------------------------------------------------------------------------
            public BoundingBox Boundingbox => Transform.GetWorldBox();
            //------------------------------------------------------------------------------------------------------------------------------------------------------
            public bool UseCollider
            {
                get => _useCollider;
                set => _useCollider = value;
            }
            #endregion

            #region [Property] EGuiPanel
            //------------------------------------------------------------------------------------------------------------------------------------------------------
            public Fbx Fbx => _fbx;
            #endregion



            //++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
            // 기본 함수
            //
            //++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++

            #region [초기화] OnCreate
            //------------------------------------------------------------------------------------------------------------------------------------------------------
            public override int OnCreate()
            {
                base.OnCreate();

                _fbx = GetComponent<Fbx>() ?? null;

                return 0;
            }
            #endregion

            #region [정리] OnDestroy
            //------------------------------------------------------------------------------------------------------------------------------------------------------
            public override int OnDestroy()
            {
                base.OnDestroy();

                _fbx = null;

                return 0;
            }
            #endregion

            #region [활성화] OnEnable
            //------------------------------------------------------------------------------------------------------------------------------------------------------
            public override int OnEnable()
            {
                base.OnEnable();

                return 0;
            }
            #endregion

            #region [비활성화] OnDisable
            //------------------------------------------------------------------------------------------------------------------------------------------------------
            public override int OnDisable()
            {
                base.OnDisable();

                return 0;
            }
            #endregion

            #region [업데이트] Update, LateUpdate
            //------------------------------------------------------------------------------------------------------------------------------------------------------
            public override void Update()
            {
                base.Update();

            }
            //------------------------------------------------------------------------------------------------------------------------------------------------------
            public override void LateUpdate()
            {
                base.LateUpdate();

            }
            #endregion

        }

    }
}
