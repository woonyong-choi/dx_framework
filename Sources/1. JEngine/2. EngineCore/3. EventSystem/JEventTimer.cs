namespace J2y
{
    //++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
    //
    // JEventTimer
    //		일정 시간 이후 이벤트 메시지를 실행한다. (임의의 게임오브젝트에 붙여서 사용할 수 있다)
    //
    //	@Events
    //		EventName (Dafult=OnEventTimerEnd)
    //
    //++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++

    public class JEventTimer : JActor, IPlayable
    {
        //++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
        // 변수
        //
        //++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++

        #region [변수] SerializeField
        public float Duration = 1f;
        public string EventName = "OnEventTimerEnd";
        #endregion

        #region [변수] 기본 변수
        protected JScheduledEvent _scheduledEvent;
        #endregion


        //++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
        // Property
        //
        //++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++

        #region [Property] State
        //------------------------------------------------------------------------------------------------------------------------------------------------------
        public bool IsPlay
        {
            get { return (_scheduledEvent != null) ? _scheduledEvent.IsPlay : false; }
        }
        #endregion



        //++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
        // Main
        //
        //++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++

        #region [생명주기] OnEnable / OnDisable
        //------------------------------------------------------------------------------------------------------------------------------------------------------
        public override int OnEnable()
        {
            base.OnEnable();
            Play();
            return 0;
        }
        //------------------------------------------------------------------------------------------------------------------------------------------------------
        public override int OnDisable()
        {
            base.OnDisable();
            Stop();
            return 0;
        }
        #endregion



        //++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
        // 메인
        //
        //++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++

        #region [IPlayable] Play
        //------------------------------------------------------------------------------------------------------------------------------------------------------
        public virtual void Play()
        {
            if (_scheduledEvent != null)
            {
                _scheduledEvent.Reset(Duration);
                _scheduledEvent.Play();
            }
            else
            {
                _scheduledEvent = JScheduler.Instance.Schedule(Duration, Finish);
            }
        }
        #endregion

        #region [IPlayable] Pause
        //------------------------------------------------------------------------------------------------------------------------------------------------------
        public virtual void Pause()
        {
            _scheduledEvent.Pause();
        }
        #endregion

        #region [IPlayable] Resume
        //------------------------------------------------------------------------------------------------------------------------------------------------------
        public virtual void Resume()
        {
            _scheduledEvent.Resume();
        }
        #endregion

        #region [IPlayable] Finish
        //------------------------------------------------------------------------------------------------------------------------------------------------------
        public virtual void Finish()
        {
            Stop();
            JEventHandler.ExecuteEvent(this, EventName);
        }
        #endregion

        #region [IPlayable] Stop
        //------------------------------------------------------------------------------------------------------------------------------------------------------
        public virtual void Stop()
        {
            _scheduledEvent?.Stop();
        }
        #endregion
    }
}
