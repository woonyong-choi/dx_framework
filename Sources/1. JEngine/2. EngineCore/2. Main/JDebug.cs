using System;


namespace J2y
{
    //++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
    //
    // JDebug
    //
    //
    //++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++

    public class JDebug
    {
        //++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
        // Assert
        //
        //++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++

        #region [Assert] 
        //------------------------------------------------------------------------------------------------------------------------------------------------------
        public static void Assert(bool valid, string message = "")
        {
            if (!valid)
            {
                JLogger.WriteError("[Assert] [NotNull]{0}", message);
                throw MakeException(message);
            }
        }
        #endregion

        #region [Assert] Null
        //------------------------------------------------------------------------------------------------------------------------------------------------------
        public static void IsNotNull(object obj, string message = "")
        {
            if (obj == null)
                JLogger.WriteError("[Assert] [NotNull]{0}", message);
        }
        //------------------------------------------------------------------------------------------------------------------------------------------------------
        public static void IsNull(object obj, string message = "")
        {
            if (obj != null)
                JLogger.WriteError("[Assert] [IsNull]{0}", message);
        }
        #endregion

        #region [Assert] AreEqual
        //------------------------------------------------------------------------------------------------------------------------------------------------------
        public static void AreEqual(object expected, object actual, string message = "")
        {
            if (!expected.Equals(actual))
                JLogger.WriteError("[Assert] [AreEqual]{0}", message);
        }
        //------------------------------------------------------------------------------------------------------------------------------------------------------
        public static void AreNotEqual(object expected, object actual, string message = "")
        {
            if (expected.Equals(actual))
                JLogger.WriteError("[Assert] [AreNotEqual]{0}", message);
        }
        #endregion


        //++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
        // Exception
        //
        //++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++

        #region [Exception] 
        //------------------------------------------------------------------------------------------------------------------------------------------------------
        public static Exception MakeException(string message)
        {
            return new Exception(message);
        }
        #endregion
    }
}
