namespace J2y
{
	//++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
	//
	// PropertyContainerComponent
	//
	//
	//++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++

	public class PropertyContainerComponent : PropertyGroup
	{
		//++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
		// 변수
		//
		//++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++

#region [변수]
		private bool _enabled;
#endregion


		//++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
		// Property
		//
		//++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++

#region [Property]
		//------------------------------------------------------------------------------------------------------------------------------------------------------
		public bool Enabled
		{
			get { return _enabled; }
			set
			{
				if (_enabled == value)
					return;
				_enabled = value;
				if (_enabled)
					JReflection.InvokeMethod(OwnerComponent, "OnEnable");
				else
					JReflection.InvokeMethod(OwnerComponent, "OnDisable");
			}
		}
#endregion


		//++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
		// 기본 함수
		//
		//++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++

#region [기본 함수]
		//------------------------------------------------------------------------------------------------------------------------------------------------------
		public PropertyContainerComponent(ComponentBase onwerComponent)
			: base(onwerComponent)
		{
			_enabled = true;
		}
#endregion


	}
}

#endif