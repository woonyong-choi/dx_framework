

#if NET_SERVER

namespace J2y
{
	//++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
	//
	// PropertyInstance
	//
	//
	//++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++

	public class PropertyInstance : PropertyGroup
	{
		//++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
		// 변수
		//
		//++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++

#region [변수]
		private string _name;
		private int _layer;
		private bool _enabled;
		private bool _show;
		private bool _locked;
#endregion


		//++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
		// Property
		//
		//++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++

#region [Property]
		//------------------------------------------------------------------------------------------------------------------------------------------------------
		public string Name
		{
			get
			{
				return _name;
			}
			set
			{
				_name = value;
			}
		}
		//------------------------------------------------------------------------------------------------------------------------------------------------------
		public int Layer
		{
			get
			{
				return _layer;
			}
			set
			{
				_layer = value;
			}
		}
		//------------------------------------------------------------------------------------------------------------------------------------------------------
		public bool Enabled
		{
			get { return _enabled; }
			set
			{
				if (_enabled == value)
					return;
				_enabled = value;
				if (_enabled)
					JReflection.InvokeMethod(OwnerComponent, "OnEnable");
				else
					JReflection.InvokeMethod(OwnerComponent, "OnDisable");
			}
		}
		//------------------------------------------------------------------------------------------------------------------------------------------------------
		public bool Show
		{
			get
			{
				return _show;
			}
			set
			{
				_show = value;
			}
		}
		//------------------------------------------------------------------------------------------------------------------------------------------------------
		public bool Locked
		{
			get
			{
				return _locked;
			}
			set
			{
				_locked = value;
			}
		}
#endregion


		//++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
		// 기본 함수
		//
		//++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++

#region [초기화]
		//------------------------------------------------------------------------------------------------------------------------------------------------------
		public PropertyInstance(ComponentBase onwerComponent)
			:this(onwerComponent, "Instance")
		{

		}
		//------------------------------------------------------------------------------------------------------------------------------------------------------
		public PropertyInstance(ComponentBase onwerComponent, string name)
			: this(onwerComponent, "Instance", true)
		{

		}
		//------------------------------------------------------------------------------------------------------------------------------------------------------
		public PropertyInstance(ComponentBase onwerComponent, string name, bool enabled, bool show = true, bool locked = false, int layer = 0)
			: base(onwerComponent)
		{
			_name		= name;
			_enabled	= enabled;
			_show		= show;
			_locked		= locked;
			_layer		= layer;
		}
#endregion
	}
}

#endif