	//++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
	//
	// PropertyGroup
	//
	//
	//++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++

	public class PropertyGroup
	{
		//++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
		// 변수
		//
		//++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++

#region [변수]
		private ComponentBase _ownerComponent;
#endregion


		//++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
		// Property
		//
		//++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++

#region [Property]
		//------------------------------------------------------------------------------------------------------------------------------------------------------
		public ComponentBase OwnerComponent
		{
			get { return _ownerComponent; } 
			protected set
			{
				_ownerComponent = value;
			}
		}
#endregion


		//++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
		// 기본 함수
		//
		//++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++

#region [기본 함수]
		//------------------------------------------------------------------------------------------------------------------------------------------------------
		public PropertyGroup(ComponentBase ownerComponent)
		{
			OwnerComponent = ownerComponent;
		}
#endregion
	}
}

#endif